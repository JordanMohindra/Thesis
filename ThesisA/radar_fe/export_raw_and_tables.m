%% EXPORT_RAW_AND_TABLES  Inputs for the on-chip range-FFT front end (radar_fe).
%  1. raw_adc_multiframe.bin : the first 50 ColoRadar frames as raw ADC samples,
%     4 RX, TDM-flattened ramps, NO DC removal, NO window - exactly what an ADC
%     interface would hand the FPGA. Layout matches coloradar_multiframe.bin:
%       header [uint32 nFrames, nSamples=256, nRamps=192, nRX=4], then per frame
%       for ramp, sample, channel: int16 I, int16 Q.
%  2. radar_fe_tables.h : the constants the HLS core uses, built from the same
%     definitions as the MATLAB chain (Matlab_Sim/preprocessing, rangeFFT,
%     compress_fx16):
%       HANN[n]  symmetric Hann, 0.5*(1-cos(2*pi*n/255)), quantised to 2^-18
%       TWC/TWS  cos/sin(2*pi*k/256), quantised to 2^-16
%       WHR/WHI  FFT of the quantised window (for removing the ramp mean after
%                the FFT), quantised to 2^-23
%  The MATLAB chain reduces to   code[k] = int16(round( X[k] / 63.75 ))
%  with X = fft(w .* (x - mean(x))) over each ramp of 256 samples (bins 0..127).

here = fileparts(mfilename('fullpath'));
addpath(fullfile(here, '..', 'Matlab_Sim'));
NFRAMES = 50; NRX = 4; N = 256;

%% ---- tables ------------------------------------------------------------
n = (0:N-1)';
w  = 0.5 * (1 - cos(2*pi*n/(N-1)));                % == hann(256), symmetric
wq = round(w * 2^18) / 2^18;
k  = (0:N/2-1)';
twc = round(cos(2*pi*k/N) * 2^16) / 2^16;
tws = round(sin(2*pi*k/N) * 2^16) / 2^16;
Wh  = fft(wq);  Wh = Wh(1:N/2);
whr = round(real(Wh) * 2^23) / 2^23;
whi = round(imag(Wh) * 2^23) / 2^23;
assert(abs(sum(w) - 127.5) < 1e-9);

fid = fopen(fullfile(here, 'radar_fe_tables.h'), 'w');
fprintf(fid, '// Generated by export_raw_and_tables.m - do not edit.\n');
fprintf(fid, '#ifndef RADAR_FE_TABLES_H\n#define RADAR_FE_TABLES_H\n#include "radar_fe_types.h"\n\n');
wr = @(name, typ, v) fprintf(fid, 'static const %s %s[%d] = {\n%s};\n\n', typ, name, numel(v), ...
    sprintf('    %.17g,\n', v));
wr('HANN', 'win_t', wq);
wr('TWC', 'tw_t', twc);
wr('TWS', 'tw_t', tws);
wr('WHR', 'wh_t', whr);
wr('WHI', 'wh_t', whi);
fprintf(fid, '#endif\n');
fclose(fid);
fprintf('radar_fe_tables.h written\n');

%% ---- raw frames ----------------------------------------------------------
[dataDir, frameFiles] = find_coloradar_data('');
fid = fopen(fullfile(here, 'raw_adc_multiframe.bin'), 'w');
fwrite(fid, uint32([NFRAMES N 192 NRX]), 'uint32');
for f = 0:NFRAMES-1
    binFile = fullfile(dataDir, sprintf('frame_%d.bin', f));
    evalc('[cube, cfg] = loadColoRadarFrame(binFile, struct(''removeDC'', false));');
    cube = cube(:, :, 1:NRX);                          % [256 x 192 x 4]
    a = zeros(2, NRX, N, size(cube, 2));
    a(1, :, :, :) = permute(real(cube), [3 1 2]);
    a(2, :, :, :) = permute(imag(cube), [3 1 2]);
    assert(all(a(:) == round(a(:))) && max(abs(a(:))) <= 32768);
    fwrite(fid, int16(a(:)), 'int16');
end
fclose(fid);
d = dir(fullfile(here, 'raw_adc_multiframe.bin'));
fprintf('raw_adc_multiframe.bin: %d bytes (%d frames)\n', d.bytes, NFRAMES);
copyfile(fullfile(here, '..', 'hls_component', 'coloradar_multiframe.bin'), ...
         fullfile(here, 'coloradar_multiframe_matlab.bin'));
fprintf('copied the MATLAB FX16 reference\n');
